#!/usr/bin/env python3
"""Generate MtaData.java of the Microbot plugin fm/mtaarena from internal/core/mta/mta.json.

A plugin package must compile on its own (hot deploys compile one package against the client
classpath), so it cannot read the Go core's table: this turns it into Java constants. The
arithmetic is written twice (internal/core/mta/mta.go and MtaCalculator.java), pinned by the
same vectors (internal/core/mta/testdata/vectors.json, copied to
microbot/src/test/resources/mta-vectors.json).

  python3 tools/gen_mta_java.py          write MtaData.java
  python3 tools/gen_mta_java.py --check  exit 1 when MtaData.java is not what mta.json yields
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "internal", "core", "mta", "mta.json")
OUT = os.path.join(
    ROOT, "microbot", "src", "main", "java", "net", "runelite", "client", "plugins", "microbot",
    "fm", "mtaarena", "MtaData.java",
)
ROOM_ORDER = ["telekinetic", "graveyard", "enchantment", "alchemist"]


def render(t):
    lines = [
        "package net.runelite.client.plugins.microbot.fm.mtaarena;",
        "",
        "/**",
        " * Generated by tools/gen_mta_java.py from internal/core/mta/mta.json (OSRS Wiki: Mage Training",
        " * Arena Shop stock and Pizazz points, CC BY-NC-SA 3.0). Do not edit: change the extractor and",
        " * regenerate.",
        " */",
        "final class MtaData",
        "{",
        "\tprivate MtaData()",
        "\t{",
        "\t}",
        "",
        "\t/** Reward: id, name, the client's item id, the wand it upgrades (or null), and its cost in",
        "\t * pizazz points per room in the order telekinetic, graveyard, enchantment, alchemist. */",
        "\tstatic final MtaReward[] REWARDS = {",
    ]
    for r in t["rewards"]:
        c = r["cost"]
        req = json.dumps(r["requires"]) if r.get("requires") else "null"
        cost = ", ".join(str(c[k]) for k in ROOM_ORDER)
        lines.append(
            f'\t\tnew MtaReward({json.dumps(r["id"])}, {json.dumps(r["name"])}, {r["item_id"]}, {req}, {cost}),'
        )
    lines += ["\t};", "", "\t/** Magic level that casts Lvl-N Enchant, indexed by N - 1. */", "\tstatic final int[] ENCHANT_MAGIC = {"]
    lines.append("\t\t" + ", ".join(str(e["magic"]) for e in sorted(t["enchant_levels"], key=lambda e: e["level"])))
    lines += ["\t};", ""]
    rooms = {r["id"]: r for r in t["rooms"]}
    for k in ROOM_ORDER:
        r = rooms[k]
        n = k.upper()
        lines.append(f'\t/** {r["name"]}: runes per point is NUM / DEN of the {r["rune"]} rune. */')
        lines.append(f'\tstatic final int {n}_NUM = {r["runes_per_point"]["num"]};')
        lines.append(f'\tstatic final int {n}_DEN = {r["runes_per_point"]["den"]};')
        lines.append(f'\tstatic final int {n}_CAP = {r["cap"]};')
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    with open(SRC, encoding="utf-8") as f:
        want = render(json.load(f))
    if args.check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != want:
            sys.exit(f"{OUT} is stale: run tools/gen_mta_java.py")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(want)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
